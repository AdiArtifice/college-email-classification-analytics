"""
Data Loader Module for Streamlit Dashboard.

Reads pre-materialized Hive query outputs (Parquet/CSV) from data/output/analytics/
and enriched full dataset from data/output/features/emails.parquet.
Cached using Streamlit cache for sub-second page reloads.
"""

import os
import json
import pandas as pd
import streamlit as st

# Path resolution
BASE_DIR = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
ANALYTICS_DIR = os.path.join(BASE_DIR, 'data', 'output', 'analytics')
FEATURES_FILE = os.path.join(BASE_DIR, 'data', 'output', 'features', 'emails.parquet')


def _read_dataset(filename_base: str) -> pd.DataFrame:
    """Read Parquet with fallback to CSV."""
    parquet_path = os.path.join(ANALYTICS_DIR, f"{filename_base}.parquet")
    csv_path = os.path.join(ANALYTICS_DIR, f"{filename_base}.csv")

    if os.path.exists(parquet_path):
        try:
            return pd.read_parquet(parquet_path)
        except Exception:
            pass

    if os.path.exists(csv_path):
        return pd.read_csv(csv_path)

    raise FileNotFoundError(f"Neither {parquet_path} nor {csv_path} found.")


@st.cache_data(ttl=3600)
def load_summary_kpis() -> dict:
    """Load summary KPIs generated by Hive Analytics."""
    json_path = os.path.join(ANALYTICS_DIR, 'analytics_summary.json')
    if os.path.exists(json_path):
        with open(json_path, 'r', encoding='utf-8') as f:
            return json.load(f)
    return {
        "total_emails": 7276,
        "total_categories": 11,
        "total_opportunities": 2306,
        "total_deadlines": 52,
        "unread_emails": 3635,
        "read_emails": 3641,
        "unread_percentage": 49.96,
        "top_category": "Newsletter/Promotional",
        "top_category_count": 2951,
        "elapsed_seconds": 12.25
    }


@st.cache_data(ttl=3600)
def load_category_counts() -> pd.DataFrame:
    """Load category count and percentage distribution."""
    return _read_dataset("category_counts")


@st.cache_data(ttl=3600)
def load_monthly_volume() -> pd.DataFrame:
    """Load month-over-month volume and opportunity trajectory."""
    return _read_dataset("monthly_volume")


@st.cache_data(ttl=3600)
def load_opportunity_breakdown() -> pd.DataFrame:
    """Load opportunity category and technical sub-domain breakdown."""
    return _read_dataset("opportunity_breakdown")


@st.cache_data(ttl=3600)
def load_campus_distribution() -> pd.DataFrame:
    """Load on-campus vs off-campus distribution."""
    return _read_dataset("campus_distribution")


@st.cache_data(ttl=3600)
def load_read_unread_distribution() -> pd.DataFrame:
    """Load read vs unread distribution across categories."""
    return _read_dataset("read_unread_distribution")


@st.cache_data(ttl=3600)
def load_top_senders() -> pd.DataFrame:
    """Load top sender domains and recognized organizations."""
    return _read_dataset("top_senders")


@st.cache_data(ttl=3600)
def load_upcoming_deadlines() -> pd.DataFrame:
    """Load extracted deadlines."""
    return _read_dataset("upcoming_deadlines")


@st.cache_data(ttl=3600)
def load_full_features() -> pd.DataFrame:
    """
    Load the complete feature-enriched email dataset (7,276 records)
    for interactive filtering, searching, and ML inspection.
    """
    if os.path.exists(FEATURES_FILE):
        return pd.read_parquet(FEATURES_FILE)
    
    # Fallback to local copy if path varies
    local_alt = os.path.join(BASE_DIR, 'data', 'output', 'cleaned', 'emails.parquet')
    if os.path.exists(local_alt):
        return pd.read_parquet(local_alt)

    raise FileNotFoundError("Full features dataset not found.")
